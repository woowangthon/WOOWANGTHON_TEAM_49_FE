import fs from 'node:fs';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
require('@next/env').loadEnvConfig(process.cwd());
const root = 'src/messages';
const locales = fs.readdirSync(root, {withFileTypes: true}).filter(e => e.isDirectory()).map(e => e.name).sort();
const selected = process.env.NEXT_PUBLIC_APP_LOCALE || 'ko';
if (!locales.includes(selected)) throw new Error(`No language pack for ${selected}`);
const baseline = fs.readdirSync(`${root}/ko`).filter(f => f.endsWith('.json')).sort();
for (const locale of locales) {
  const names = fs.readdirSync(`${root}/${locale}`).filter(f => f.endsWith('.json')).sort();
  if (JSON.stringify(names) !== JSON.stringify(baseline)) throw new Error(`Namespace mismatch: ${locale}`);
  for (const name of names) {
    const keys = Object.keys(JSON.parse(fs.readFileSync(`${root}/${locale}/${name}`, 'utf8'))).sort();
    const expected = Object.keys(JSON.parse(fs.readFileSync(`${root}/ko/${name}`, 'utf8'))).sort();
    if (JSON.stringify(keys) !== JSON.stringify(expected)) throw new Error(`Message key mismatch: ${locale}/${name}`);
  }
  const imports = names.map((name, i) => `import namespace${i} from './${name}';`).join('\n');
  fs.writeFileSync(`${root}/${locale}/index.ts`, `// Generated by scripts/generate-i18n.mjs\n${imports}\nconst messages = {${names.map((name, i) => `${JSON.stringify(name.slice(0, -5))}: namespace${i}`).join(', ')}};\nexport default messages;\n`);
}
fs.writeFileSync('src/i18n/catalog.generated.ts', `// Generated by scripts/generate-i18n.mjs; select a deployment locale with NEXT_PUBLIC_APP_LOCALE.\nexport {default as activeMessages} from '@/messages/${selected}';\nexport const activeLocale = ${JSON.stringify(selected)} as const;\nexport const locales = ${JSON.stringify(locales)} as const;\nexport const messageLoaders = {${locales.map(locale => `${JSON.stringify(locale)}: () => import('@/messages/${locale}').then(module => module.default)`).join(', ')}};\n`);
